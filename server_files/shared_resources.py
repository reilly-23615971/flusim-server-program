def clear_files(files: set[str]):
    """
    Function to remove files generated by a simulation run after it is complete

    Parameters:
        files (set of str): A list of paths to files that must be removed.
    """
    # TODO: See if tempfile can replace this workaround
    # TODO: Make sure files are deleted some time after a websocket breaks
    print("[clear_files] Deleting the following files for cleanup purposes:")
    for f in files:
        print("   ", f, end="")
        try:
            os.remove(f)
            print()
        except FileNotFoundError:
            # Note files that already didn't exist
            print(" (not found)")


async def update_status(sim: TaskData, state: str, extra: dict = {}):
    """
    Simple async function to update the returned status of a server operation.

    Parameters:
        sim (TaskData): The object containing the data used for this simulation.

        state (str): The state to set the task to.

        extra (dict): Additional JSON attributes to include in the status
            message.
    """
    # TODO: If other tasks don't use TaskData modify the parameters here
    sim.status = state

    # Broadcast to connected WebSockets
    message = {"status": state} | extra
    if not sim.websockets:
        shared_log.warning(
            f"Task {sim.task_id} had no websockets it could update to {message}\n"
        )
    for websocket in sim.websockets:
        try:
            await websocket.send_json(message)
            shared_log.info(f"Status for {sim.task_id} updated to {message}\n")
        except Exception as e:
            shared_log.error(f"""
Status for {sim.task_id} wasn't updated to {message} due to the following error:
{e}\n
            """)


def display_time(start_time: datetime) -> str:
    """
    Calculates the time since a given point and displays it in mm:ss format

    Parameters:
        start_time (datetime): The point in time to measure from.

    Returns:
        str: The time between start_time and now, as a string in mm:ss format.
    """
    end_time = datetime.now()
    total_time = end_time - start_time
    seconds = str(total_time.seconds % 60).zfill(2)
    return f"{total_time.seconds // 60}:{seconds}"
