def generate_toolbox_config(
    sim: TaskData, file_id: Optional[str], joint: Optional[str]
) -> str:
    """
    Function to generate the required toolbox config file for a simulation
    experiment

    Parameters:
        sim (TaskData): The object containing the data used for this simulation.

        file_id (str): The numeric identifier for the files generated for this
            simulation, stored as a string.

        joint (str): A string used to label files generated by the simulation.

    Returns:
        str: The file path for the newly created configuration file.
    """
    toolbox_config_settings = {
        "simulator_executable": "src/simulator/build/src/simulator",
        "baseline_file": "conf/simulation.baseline.json",
        "middle_joint": joint,
        "set_id_joint": "-",
        "event_suffix": ".sqlite",
        "input_directory": "results/",
        "output_directory": "post-analysis",
        "communities": [
            {"name": "newcastle", "path": "communities/newcastle2011"},
            {"name": "cairns", "path": "communities/cairns2011"},
            {"name": "integration", "path": "integration/community"},
        ],
    }

    # Log filename preemptively in case of cancellation
    toolbox_config_path = f"temp-files/toolbox_config_{file_id}.json"
    sim.files.add(toolbox_config_path)
    print(
        "[generate_toolbox_config] Generating toolbox "
        f"configuration file {toolbox_config_path}"
    )
    with open(toolbox_config_path, "w") as file:
        json.dump(toolbox_config_settings, file, indent=2)
    return toolbox_config_path


async def run_simulation(
    sim: TaskData,
    file_id: Optional[str],
    config_data: ModelGuideFile,
    toolbox_path: str,
):
    """
    Function to run a simulation experiment using the given config files

    Parameters:
        sim (TaskData): The object containing the data used for this simulation.

        file_id (str): The numeric identifier for the files generated for this
            simulation, stored as a string.

        config_data (ModelGuideFile): The parameters and other settings that
            will define the simulation experiment.

        toolbox_path (str): The path to the file containing settings for the
            toolbox commands.
    """
    # from commands.Run.RunCommand import RunCommand
    from server_files.toolbox_overrides import RunCommandWithTask

    run_start_time = datetime.now()
    toolbox_config = ToolboxConfiguration(toolbox_path)

    guide_path = f"temp-files/flusim-{file_id}.guide.json"

    # Get list of sim files so they can be deleted once the
    # simulation and analysis are complete
    simulation_files = {
        os.path.join(
            SIMULATOR_LOCATION,
            "results",
            (
                (
                    f"{config_data.community_used[0]}{config_data.middle_joint}"
                    f"{config_data.simulation_sets[0].version}-{i:02}.sqlite"
                )
            ),
        )
        for i in range(len(config_data.simulation_sets[0].simulations))
    }

    # Log files preemptively in case of cancellation
    sim.files |= simulation_files | {guide_path}

    with open(guide_path, "w") as file:
        file.write(config_data.model_dump_json(indent=2, exclude_unset=True))

    # Run the simulation
    await RunCommandWithTask(sim=sim).run_command_async(
        Namespace(guide=guide_path, log_level=LogLevel.DEBUG), toolbox_config
    )
    print(
        "[run_simulation] Finished running the simulation experiment "
        f"in {display_time(run_start_time)}\n"
    )


def epidemic_filename(options: Namespace, config: ToolboxConfiguration) -> str:
    """
    Function to construct the proper file name for epidemic results

    Parameters:
        options: The arguments for the epidemic command.

        config: The configuration settings for this simulation.

    Returns:
        str: The name of the generated file.
    """
    filename = ""

    if len(options.community) > 0:
        filename += ",".join(options.community)
    filename += config.middle_joint
    if len(options.set) > 0:
        filename += ",".join([str(s) for s in options.set])
    if len(options.filenames) > 0:
        filename += "+others"
    filename += "-epidemic-"

    if options.cumulative_sum:
        filename += "cumulative-"
    filename += f"{options.calculate_stat}"

    if not options.scale == 1.0:
        filename += f"-scale_{options.scale:.5g}"
    if options.age_adjusted is not None:
        filename += "-age_adjusted"
    if options.by_strain:
        filename += "-by_strain"
    if options.by_age:
        filename += "-by_age"
    if options.by_vaccine:
        filename += "-by_vaccine"

    return filename + ".csv"


def epidemic(
    sim: TaskData,
    file_id: Optional[str],
    community_name: CommunityName,
    summary_stat=None,
    cumulative=False,
    by_age=False,
    toolbox_path: Optional[str] = None,
) -> list[str]:
    """
    Wrapper to run the epidemic toolbox command on a given simulation output,
    generating epidemic curves in CSV format

    Parameters:
        sim (TaskData): The object containing the data used for this simulation.

        file_id (str): The numeric identifier for the files generated for this
            simulation, stored as a string.

        community_name (str): The name of the community being simulated (e.g.
            Newcastle).

        summary_stat (AnalysisStat, optional): Which summary statistic to use
            when generating the analysis data. Defaults to Median; None is
            converted to Median for import formatting purposes.

        cumulative (bool): Set to True if you want to generate cumulative
            infections over time instead of daily infections.

        by_age (bool): Set to True if you want to generate separate epidemic
            curves for each age group.

        toolbox_path (str, optional): The path to the file containing settings
            for the toolbox commands.

    Returns:
        list of str: The name of the CSV files containing the generated
            epidemic curve(s), wrapped in a list to avoid issues when
            listing the required files.
    """
    from commands.epidemic import EpidemicCurveCommand

    epidemic_start_time = datetime.now()
    if summary_stat is None:
        summary_stat = AnalysisStat.MEDIAN
    valid_path = (
        toolbox_path if toolbox_path else f"temp-files/toolbox_config_{file_id}.json"
    )
    toolbox_config = ToolboxConfiguration(valid_path)

    # Run epidemic analysis
    # TODO: Integrate other options as params if needed by the dashboard
    epidemic_args = Namespace(
        community=[community_name],
        set=[file_id],
        calculate_stat=summary_stat,
        cumulative_sum=cumulative,
        by_age=by_age,
        moving_average_window=7,
        scale=1,
        by_strain=False,
        by_vaccine=False,
        age_adjusted=None,
        split_output=False,
        filenames=[],
        log_level=LogLevel.DEBUG,
    )
    print(
        "[epidemic] Running 'epidemic' analysis for "
        f"set {file_id} on community {community_name}"
    )
    print(
        f"Options: [{summary_stat}]",
        "[cumulative]" if cumulative else "[individual]",
        "[age-separated]" if by_age else "[age-combined]",
    )
    # Log files preemptively in case of cancellation
    filename = os.path.join(
        SIMULATOR_LOCATION,
        "post-analysis",
        epidemic_filename(epidemic_args, toolbox_config),
    )
    sim.files |= {filename}

    # TODO: More fine-grain progress for epidemic
    EpidemicCurveCommand().run_command(epidemic_args, toolbox_config)

    # Sort file and fill null values
    ordered_epidemic_data = (
        pd.read_csv(filename, header=0).sort_index(axis=1).set_index("day")
    )
    if cumulative:
        ordered_epidemic_data = ordered_epidemic_data.ffill()
    ordered_epidemic_data.to_csv(filename, na_rep="0.0")
    print(
        "[epidemic] Finished running epidemic analysis "
        f"in {display_time(epidemic_start_time)}\n"
    )
    return [filename]


# Function for asir toolbox function
def asir(
    sim: TaskData,
    file_id: Optional[str],
    community_name: CommunityName,
    joint: Optional[str],
    summary_stat=None,
    proportion=False,
    indigenous_only=False,
    pregnant_only=False,
    vaccinated_only=False,
    toolbox_path: Optional[str] = None,
) -> list[str]:
    """
    Wrapper to run the asir toolbox command on a given simulation output,
    generating age-separated infection rates in CSV format.

    Parameters:
        sim (TaskData): The object containing the data used for this simulation.

        file_id (str): The numeric identifier for the files generated for this
            simulation, stored as a string.

        community_name (str): The name of the community being simulated (e.g.
            Newcastle).

        joint (str): A string used to label files generated by the simulation.

        summary_stat (AnalysisStat, optional): Which summary statistic to use
            when generating the analysis data. Defaults to Median; None is
            converted to Median for import formatting purposes.

        proportion (bool): Set to True if you want to generate infection
            rates as proportions of the population rather than exact values.

        indigenous_only (bool): Set to True if you want to generate rates for
            indigenous people specifically.

        pregnant_only (bool): Set to True if you want to generate rates for
            pregnant people specifically.

        vaccinated_only (bool): Set to True if you want to generate rates for
            vaccinated people specifically.

        toolbox_path (str, optional): The path to the file containing settings
            for the toolbox commands.

    Returns:
        list of str: The name of the CSV file containing the generated rates,
            wrapped in a list to avoid issues when listing the required files.
    """
    from commands.ASIRAnalysis import AsirCommand

    asir_start_time = datetime.now()
    if summary_stat is None:
        summary_stat = AnalysisStat.MEDIAN
    valid_path = (
        toolbox_path if toolbox_path else f"temp-files/toolbox_config_{file_id}.json"
    )
    toolbox_config = ToolboxConfiguration(valid_path)

    # Log files preemptively in case of cancellation
    file_stem = f"{community_name}{joint}{file_id}-asir-{summary_stat}"
    old_filename = os.path.join(SIMULATOR_LOCATION, "post-analysis", f"{file_stem}.csv")
    new_filename = os.path.join(
        SIMULATOR_LOCATION,
        "post-analysis",
        f"{file_stem}{'-proportion' if proportion else '-discrete'}"
        f"{'-indigenous_only' if indigenous_only else '-all_demographics'}"
        f"{'-pregnant_only' if pregnant_only else '-all_pregnancy'}"
        f"{'-vaccinated_only' if vaccinated_only else '-all_vaccination'}.csv",
    )
    sim.files |= {old_filename, new_filename}

    # Run epidemic analysis
    asir_args = Namespace(
        community=[community_name],
        set=[file_id],
        calculate_stat=summary_stat,
        proportion=proportion,
        indigenous=indigenous_only,
        pregnant=pregnant_only,
        vaccinated=vaccinated_only,
        filenames=[],
        log_level=LogLevel.DEBUG,
    )
    print(
        "[asir] Running 'asir' analysis for set "
        f"{file_id} on community {community_name}"
    )
    print(
        f"Options: [{summary_stat}]",
        "[proportionate]" if proportion else "[discrete]",
        "[indigenous only]" if indigenous_only else "[all demographics]",
        "[pregnant only]" if pregnant_only else "[all pregnant status]",
        "[vaccinated only]" if vaccinated_only else "[all vaccine status]",
    )
    # TODO: More fine-grain progress for asir
    AsirCommand().run_command(asir_args, toolbox_config)

    # Rename file to account for all options and avoid overwriting previous data
    # TODO: Just modify the toolbox to include all parameters in the name
    os.rename(old_filename, new_filename)

    # Order the scenarios correctly
    ordered_asir_data = pd.read_csv(new_filename, header=0, index_col=0).sort_index()
    ordered_asir_data.to_csv(new_filename, na_rep="0.0")

    print(f"[asir] Finished running asir analysis in {display_time(asir_start_time)}\n")
    return [new_filename]
