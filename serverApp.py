# Define task for receiving model parameters
async def runModel(simulationID: int, config: modelGuideFile):
    """
    Async function to run a simulation experiment based on parameters
    from the dashboard, then zip the analysed statistics.

    Parameters:
        simulationID (int): The ID distinguishing this simulation task.

        config (modelGuideFile): The parameters and other settings that
            will define the simulation experiment.
    """
    try:
        overallStartTime = datetime.now()
        await updateStatus(simulationID, "start")
        # TODO: More status updates

        # Get relevant attributes from config file
        # TODO: See if sessionID can be replaced with simulationID
        sessionID = config.description
        community = config.community_used[0]
        middleJoint = config.middle_joint
        print(f"Simulation received; name = {config.name}, ID = {sessionID}")

        # Generate toolbox config file
        toolboxPath = generateToolboxConfig(sessionID, middleJoint)
        print(f"Toolbox file located at {toolboxPath}")

        # Run the Flusim simulation
        createdFiles = runSimulation(config, toolboxPath)
        analysisFiles = []

        # TODO: Use middle joint to determine analyses to run
        # (or find a way to send the data forms to the server directly)
        middleCheck = """if middleJoint:
            # Epidemic tool
            if 'usingEpidemic' in middleJoint:
                sumStat = (
                    AnalysisStat.MEAN if 'EMean' in middleJoint
                    else AnalysisStat.MEDIAN
                )
                epiCumulative = 'ECumulative' in middleJoint
                epiAge = 'EAgeBased' in middleJoint
                analysisFiles.append(epidemic(
                    community, middleJoint, sessionID, summaryStat = sumStat,
                    cumulative = epiCumulative, byAge = epiAge,
                    toolboxPath = toolboxPath
                ))
            # Asir tool
            if 'usingAsir' in middleJoint:
                sumStat = (
                    AnalysisStat.MEAN if 'AMean' in middleJoint
                    else AnalysisStat.MEDIAN
                )
                asirProportion = 'AProportion' in middleJoint
                asirIndigenous = 'AIndigenous' in middleJoint
                asirPregnant = 'APregnant' in middleJoint
                asirVaccinated = 'AVaccinated' in middleJoint
                analysisFiles.append(asir(
                    community, middleJoint, sessionID,
                    summaryStat = sumStat, getProportion = asirProportion,
                    onlyIndigenous = asirIndigenous, onlyPregnant = asirPregnant,
                    onlyVaccinated = asirVaccinated, toolboxPath = toolboxPath
                ))"""
        # for now, just get the standard analyses the dashboard uses

        # Daily infection epidemic curve
        analysisFiles += epidemic(
            community, middleJoint, sessionID, cumulative=True, toolboxPath=toolboxPath
        )

        # Cumulative infection epidemic curve
        analysisFiles += epidemic(
            community,
            middleJoint,
            sessionID,
            cumulative=False,
            toolboxPath=toolboxPath,
        )

        # Age-separated infection rates
        analysisFiles += asir(
            community, middleJoint, sessionID, toolboxPath=toolboxPath
        )

        # Vaccinated age-separated infection rates
        if middleJoint and "+vaccine" in middleJoint:
            analysisFiles += asir(
                community,
                middleJoint,
                sessionID,
                onlyVaccinated=True,
                toolboxPath=toolboxPath,
            )

        # If all else fails and no analyses were specified, run epidemic
        if not analysisFiles:
            print("No analyses specified; defaulting to epidemic")
            analysisFiles += epidemic(
                community, middleJoint, sessionID, toolboxPath=toolboxPath
            )

        print("\nAnalysis files:")
        for file in analysisFiles:
            print("   ", file)

        # Zip together the analysis files if necessary
        # TODO: See if simplifying to always return zip is OK
        if len(analysisFiles) != 1:
            zipPath = f"tempFiles/{sessionID}_analysis.zip"
            with zipfile.ZipFile(zipPath, mode="w") as analysis:
                for file in analysisFiles:
                    analysis.write(file)
            createdFiles.add(zipPath)
            finalPath = zipPath
        # Just return lone CSV if only one analysis needed
        else:
            (finalPath,) = analysisFiles

        print(
            f"\nSimulation request for session {sessionID} complete in "
            f"{displayTime(overallStartTime)}, returning data\n"
        )

        completedSimulations[simulationID] = (
            finalPath,
            createdFiles | {toolboxPath}.union(analysisFiles),
        )

        await updateStatus(simulationID, "completed")
    except Exception as e:
        # TODO: Update error status
        await updateStatus(simulationID, "error")
        print(f"Error while running simulation {simulationID}:\n{e}")


# Define route for receiving model parameters
@flusimApp.post("/runModel")
async def runModelRoute(config: modelGuideFile) -> dict[str, int]:
    """
    Async route function to begin a simulation experiment and give the
    dashboard an ID to poll for status updates.

    Parameters:
        config (modelGuideFile): The parameters and other settings that
            will define the simulation experiment.

    Returns:
        dict: A dictionary containing the ID assigned to this particular
            simulation run. A dictionary is used rather than returning the ID
            directly as an int to ensure corrupted data is not read by the
            dashboard client.
    """
    simulationID = uuid.uuid4().int

    asyncio.create_task(runModel(simulationID, config))

    return {"simulationID": simulationID}


@flusimApp.get("/runModel/status/{simulationID}")
async def getSimulationStatus(simulationID: int):
    """
    Async route function to check the current progress of a simulation experiment.

    Parameters:
        simulationID (int): The ID distinguishing this simulation task.

    Returns:
        dict: A dictionary containing the ID assigned to this particular
            simulation run. A dictionary is used rather than returning the ID
            directly as an int to allow for error messages to be sent if the
            task does not exist.
    """
    return simulationStatus.get(simulationID, {"error": "Task not found"})


@flusimApp.get("/runModel/download/{simulationID}")
async def downloadSimulationResults(simulationID: int, cleanup: BackgroundTasks):
    """
    Async route function to obtain the results of a simulation experiment.

    Parameters:
        simulationID (int): The ID distinguishing this simulation task.

        cleanup (BackgroundTasks): An object that will have file removal
            functions attached to it to remove excess files once this
            function finishes running.
    """
    if simulationID not in simulationStatus:
        return {"error": "Task not found"}

    currentStatus = simulationStatus[simulationID]
    if currentStatus != "completed":
        return {"error": "Task not completed", "status": currentStatus}

    filePath, filesToDelete = completedSimulations.get(simulationID, (None, None))

    if not filePath or not os.path.exists(filePath):
        return {"error": "File not found"}

    # TODO: Allow preserving these files until the client is disconnected
    if deleteFiles:
        cleanup.add_task(clearFiles, filesToDelete)

    # TODO: Remove the dictionary entries once finished

    return FileResponse(filePath, filename=os.path.basename(filePath))
